"""Build or verify the model explorer's read-only excerpt of registered SAE features."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path("tests/glm5/result/mlp_fidelity_v2")
AUDIT = Path("research/mlp_fidelity/v2/storage-audit-f332509210df.research.json")
TARGET = ROOT / "frontend/src/components/v8/sparseDictionaryArchive.js"
BLOCKS = [8, 24, 35]


def checksum(data):
    return hashlib.sha256(data).hexdigest()


def read_report(path):
    raw = (ROOT / path).read_bytes()
    return json.loads(raw), {"path": path.as_posix(), "sha256": checksum(raw)}


def extract():
    plan, plan_source = read_report(SOURCE / "plan.json")
    audit, audit_source = read_report(AUDIT)
    run = plan["run_id"]
    snapshot = plan["model_snapshot"]
    if run != "MLP-FIDELITY-20261104-v2" or snapshot != "6be1034f0b55a6dfc9383b4f155a736433d822a21f3ab6178012c2c2e14739ad":
        raise ValueError("Unexpected run or model snapshot")
    if (audit["run_id"], audit["model_snapshot"]) != (run, snapshot):
        raise ValueError("Independent storage audit identity mismatch")
    hashes = {p.replace("\\", "/"): sha for p, sha in audit["files"].items()}
    result = {
        "run": run, "snapshot": snapshot, "model": "Qwen3-4B", "blocks": BLOCKS,
        "plan": plan_source, "historicalAudit": audit_source, "layers": [],
    }
    for block in BLOCKS:
        filename = f"B{block:02d}-result.json"
        trained, training_source = read_report(SOURCE / "trained" / filename)
        evaluation, evaluation_source = read_report(SOURCE / "fresh-evaluation" / filename)
        semantic, semantic_source = read_report(SOURCE / "semantics-v2" / filename)
        for report in [trained, evaluation, semantic]:
            if (report["kind"], report["run_id"], report["model_snapshot"], report["block"]) != ("real", run, snapshot, block):
                raise ValueError(f"B{block} report identity mismatch")
        candidate = trained["candidate"]
        dictionary_path = trained["state_path"].replace("\\", "/")
        sha = trained["state_sha256"]
        if (candidate != evaluation["candidate"] or candidate["kind"] != "sae_output"
                or evaluation["dictionary_sha256"] != sha or hashes.get(dictionary_path) != sha):
            raise ValueError(f"B{block} trained dictionary identity mismatch")
        if semantic["fidelity_gate"] != evaluation["both_fidelity_gates"]:
            raise ValueError(f"B{block} fidelity gate mismatch")
        confirm, lockbox = evaluation["results"]["confirm"], evaluation["results"]["lockbox"]
        features = []
        for f in semantic["features"]:
            counter = f["response_counterexample"]
            if (not 0 <= f["feature"] < candidate["m"] or len(f["replicated_by_readout"]) != 2
                    or counter["is_sign_failure"] != (counter["oriented_delta"] <= 0)):
                raise ValueError(f"B{block} inconsistent feature record")
            features.append({
                "id": f["feature"], "nomination": f["nomination_factor"], "replicated": f["replicated_by_readout"],
                "eligible": f["functional_eligible"], "signFailure": counter["is_sign_failure"],
                "counterexampleIndices": counter["indices"], "orientedDelta": counter["oriented_delta"],
            })
        if len({f["id"] for f in features}) != len(features):
            raise ValueError(f"B{block} duplicated feature index")
        result["layers"].append({
            "block": block, "dictionaryPath": dictionary_path, "dictionarySha": sha,
            "k": candidate["k"], "m": candidate["m"], "confirmFVU": confirm["FVU"]["dictionary"],
            "lockboxFVU": lockbox["FVU"]["dictionary"], "fidelityGate": semantic["fidelity_gate"],
            "behaviorGate": semantic["behavior_gate"], "features": features,
            "sources": [training_source, evaluation_source, semantic_source],
        })
    return result


def main():
    flags = argparse.ArgumentParser(description=__doc__)
    flags.add_argument("--write", action="store_true", help="regenerate the bundled JS after verifying the source reports")
    args = flags.parse_args()
    excerpt = extract()
    content = ("// Generated by tests/glm5/export_sparse_dictionary_archive.py --write.\n"
               "globalThis.AI2050SparseDictionary = " + json.dumps(excerpt, ensure_ascii=False, indent=2)
               + ";\n").encode()
    if args.write:
        sys.path.insert(0, str(ROOT))
        from deploy.storage_policy import check_write
        check_write(TARGET.parent, len(content) * 2, operation="导出机制字典插件档案")
        TARGET.write_bytes(content)
    elif TARGET.read_bytes() != content:
        raise SystemExit("SAE archive differs from verified reports; investigate before regenerating")
    print(f"Verified {sum(len(layer['features']) for layer in excerpt['layers'])} feature records from 3 layers, 9 reports, frozen plan and historical dictionary hashes.")


if __name__ == "__main__":
    main()
