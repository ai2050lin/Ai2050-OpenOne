"""New post-selection diagnostic: frozen rules on known native free histories.

No native model/head loads or fitting. This is not autonomous prediction: every
prefix is the original model's actual past, and only that past's early features
are supplied. Later targets/IDs never enter the frozen prediction function.
"""
import argparse
from collections import defaultdict
from rdc_question_common import *
from rdc_question_predictor import FrozenPredictor
import rdc_question_data as data

BIN_NAMES=['first','later_all','step1','step2to3','step4to7','step8plus']
COLUMNS=['prediction_MSE','training_mean_MSE','native_norm_squared_mean',
    'prediction_norm_squared_mean','native_centered_energy','prediction_centered_energy',
    'centered_response_inner_product','query_standardized_RMS','context_standardized_RMS']


def membership(step):
    return ['first'] if step==0 else ['later_all','step1' if step==1 else 'step2to3' if step<4 else 'step4to7' if step<8 else 'step8plus']


def freeze(key):
    path=OUT/'native_history_prediction'/key/'execution.json'
    execution={'source':snapshot(__file__),'predictor':snapshot(Path(__file__).with_name('rdc_question_predictor.py')),
        'selection_sha256':sha(OUT/'fit'/key/'validation_selection.json'),
        'native_result_sha256':sha(OUT/f'native/{key}/nonconfirmation/result.json')}
    if path.exists():
        old=read(path);assert old['execution']==execution;return old
    unit=read(OUT/'unit'/('predictor_'+key+'_current.json'))
    assert unit['all_passed'] and unit['predictor']['sha256']==execution['predictor']['sha256']
    spec={'timestamp':stamp(),'execution':execution,'unit_sha256':sha(OUT/'unit'/('predictor_'+key+'_current.json')),
        'new_diagnostic_design':'Added after native first-prefix/behavior diagnostics and all rule selection, before this script reads any later native target. Not a retrospectively declared preregistration.',
        'inputs':'At each actual native free prefix, H12last, block12native source read, and unchanged separately consumed contextH12mean. Actual postnorm only scores; nextnative tokenID only labels.',
        'rules':'Exactly the already selected primary and within-context-target-shuffle control. No new fit, hyperparameter, input or checkpoint selection.',
        'splits':['validation','diagnostic'],'bins':BIN_NAMES,
        'estimands':'Token means, and within-bin token means per question then means over questions within context then contexts within cohort. Main comparison later_all. step8plus is conditional on surviving histories, not the unconditional original population.',
        'baseline':'Frozen unshuffled training first-prefix postnorm mean; cannot stand for a later-position-aware baseline.',
        'bootstrap':'2000wholecontexts independently within cohort, seeds2748010/2748011; paired predicted-minus-mean and primary-minus-null; descriptive95percent, no multiplicity adjustment.',
        'retention':'All token metrics/identities and all coordinate error/energy means by cohort/split/bin retained. Full predicted vectors recoverable from unchanged earlyhistoryfields and exact retained coefficients; not all predictions duplicated.',
        'limits':'Native-policy prefixes are given, not generated by the predictor. Even good later-state fitting would not prove the predictor generates those histories. No vocabulary KL or answer claim in this CPU-only stage.'}
    immutable(path,spec);return spec


def group_estimate(items,metric):
    by_context=defaultdict(list)
    for r in items:by_context[r['group_id']].append(r['means'][metric])
    values=np.array([np.mean(by_context[gid]) for gid in sorted(by_context)])
    return values


def pair_summary(items,left,right):
    result={};draws=[]
    for cohort in ['drop','quoref']:
        rr=[r for r in items if r['cohort']==cohort]
        if not rr:
            result[cohort]={'contexts':0,'questions':0};continue
        a=group_estimate(rr,left);b=group_estimate(rr,right);delta=a-b
        rng=np.random.default_rng(2748010+(cohort=='quoref'))
        samples=delta[rng.integers(0,len(delta),(2000,len(delta)))].mean(1)
        draws.append(samples)
        result[cohort]={'contexts':len(delta),'questions':len(rr),'tokens':sum(r['tokens']for r in rr),
            'left_mean':float(a.mean()),'right_mean':float(b.mean()),'mean_left_minus_right':float(delta.mean()),
            'paired_whole_context_interval95':np.quantile(samples,[.025,.975]).tolist()}
    if len(draws)==2:
        result['equal_cohort']={k:float(np.mean([result[c][k]for c in ['drop','quoref']]))for k in ['left_mean','right_mean','mean_left_minus_right']}
        result['equal_cohort']['paired_whole_context_interval95']=np.quantile((draws[0]+draws[1])/2,[.025,.975]).tolist()
    return result


def main(key):
    start=time.monotonic();spec=freeze(key);folder=Path('native_history_prediction')/key
    final=OUT/folder/'result.json'
    if final.exists():
        assert read(final)['execution_sha256']==sha(OUT/folder/'execution.json')
        print('NATURAL_NATIVE_HISTORY_PREDICTION_ALREADY_COMPLETE',key,flush=True);return
    selection=read(OUT/'fit'/key/'validation_selection.json')
    rules=[FrozenPredictor(key,v)for v in [selection['primary_rule'],selection['control_rule']]]
    all_results=[];all_question_bins={}
    for split in ['validation','diagnostic']:
        rows,groups,questions=data.index(key,{split})
        means={gid:data.field(g['context_field'],['context_H12_mean'])['context_H12_mean']for gid,g in groups.items()}
        for rule in rules:
            resultpath=OUT/folder/rule.variant/(split+'.json')
            if resultpath.exists():
                old=read(resultpath);assert old['predictor']==rule.identity
                assert sha(ROOT/old['question_bins']['path'])==old['question_bins']['sha256']
                all_question_bins[(rule.variant,split)]=gzread(ROOT/old['question_bins']['path']);all_results.append(old);continue
            records=[];point_values=[];qbin=[];coord={};first=[]
            for qi,row in enumerate(rows):
                qid=row['question_id'];record=questions[qid]['history'];ref=record['field']
                values=data.field(ref,['H12_last_BF16','native_source_read_BF16','postnorm_BF16','generated_ids','positions'])
                h,rd,y=values['H12_last_BF16'],values['native_source_read_BF16'],values['postnorm_BF16']
                context=np.repeat(means[row['group_id']][None],len(h),axis=0)
                # Prediction is complete before y enters any arithmetic below.
                prediction=rule.predict(h,rd,context)
                targetmean=rule.values['target_mean'];err=(prediction-y)**2
                base=(targetmean-y)**2;yc=y-targetmean;pc=prediction-targetmean
                qvalue=np.concatenate([h,rd],axis=1)if rule.variant=='native_source_read'else h
                scaledq=(qvalue-rule.values['query_mean'])/rule.values['query_scale']
                scaledc=(context-rule.values['context_mean'])/rule.values['context_scale']
                scores=np.stack([err.mean(1),base.mean(1),(y*y).mean(1),(prediction*prediction).mean(1),
                    (yc*yc).mean(1),(pc*pc).mean(1),(yc*pc).mean(1),np.sqrt((scaledq*scaledq).mean(1)),np.sqrt((scaledc*scaledc).mean(1))],axis=1)
                assert np.isfinite(scores).all() and len(h)==len(record['generated_ids'])
                first.append(float(scores[0,0]))
                point_values.extend(scores)
                records.extend({'question_id':qid,'group_id':row['group_id'],'cohort':row['cohort'],'split':split,
                    'step':s,'native_next_id':record['generated_ids'][s],'position':int(values['positions'][s]),
                    'native_complete_exact_and_stopped':record['score']['whole_response_exact_and_stopped']}for s in range(len(h)))
                for name in BIN_NAMES:
                    take=[s for s in range(len(h))if name in membership(s)]
                    if not take:continue
                    qbin.append({'question_id':qid,'group_id':row['group_id'],'cohort':row['cohort'],'split':split,'bin':name,
                        'tokens':len(take),'means':{c:float(scores[take,i].mean())for i,c in enumerate(COLUMNS)}})
                    ident=row['cohort']+'__'+name
                    if ident not in coord:coord[ident]={'n':0,**{k:np.zeros(y.shape[1])for k in ['prediction_error','mean_error','native_centered_energy','predicted_centered_energy','centered_innerproduct']}}
                    a=coord[ident];a['n']+=len(take)
                    for k,v in [('prediction_error',err),('mean_error',base),('native_centered_energy',yc**2),('predicted_centered_energy',pc**2),('centered_innerproduct',yc*pc)]:a[k]+=v[take].sum(0)
                if (qi+1)%48==0:print('NATURAL_NATIVE_HISTORY_PREDICTION',key,split,rule.variant,qi+1,len(rows),round(time.monotonic()-start,1),flush=True)
            original=read(OUT/'fit'/key/rule.variant/'evaluation.json')
            originalref=next(r['field']for r in original['evaluations']if r['kind']=='selected'and r['target']=='postnorm'and r['split']==split)
            assert sha(ROOT/originalref['path'])==originalref['sha256']
            with np.load(ROOT/originalref['path'])as z:
                first_error=float(np.max(np.abs(z['absolute_MSE_by_question']-first)))
                assert first_error<1e-8,first_error
            arrays={'all_token_metrics':np.stack(point_values)}
            for ident,a in coord.items():
                for name,value in a.items():
                    if name!='n':arrays[ident+'__'+name+'__token_mean']=value/a['n']
            reference=commit_arrays(folder/rule.variant,split,arrays)
            identities=OUT/folder/rule.variant/(split+'_identities.json.gz')
            binsfile=OUT/folder/rule.variant/(split+'_question_bins.json.gz')
            assert not identities.exists()and not binsfile.exists()
            compressed(identities,records);compressed(binsfile,qbin)
            summaries=[{'bin':name,'prediction_minus_training_mean':pair_summary([r for r in qbin if r['bin']==name],'prediction_MSE','training_mean_MSE')}for name in BIN_NAMES]
            result={'model':key,'variant':rule.variant,'split':split,'predictor':rule.identity,
                'questions':len(rows),'tokens':len(records),'columns':COLUMNS,'field':reference,
                'all_first_prefix_MSE_maximum_difference_from_original_fit':first_error,
                'identities':{'path':identities.relative_to(ROOT).as_posix(),'sha256':sha(identities)},
                'question_bins':{'path':binsfile.relative_to(ROOT).as_posix(),'sha256':sha(binsfile)},
                'summaries':summaries,'coordinate_aggregation':'Token-weighted mean for each cohort/bin; no coordinate dropped. Inferential scalar summaries are question/context balanced separately.'}
            immutable(resultpath,result);all_results.append(result);all_question_bins[(rule.variant,split)]=qbin
    paired=[]
    for split in ['validation','diagnostic']:
        primary=all_question_bins[(selection['primary_rule'],split)]
        control=all_question_bins[(selection['control_rule'],split)]
        lookup={(r['question_id'],r['bin']):r for r in control}
        rows=[]
        for row in primary:
            other=lookup[(row['question_id'],row['bin'])]
            assert other['tokens']==row['tokens']
            rows.append({**row,'means':{'primary':row['means']['prediction_MSE'],'control':other['means']['prediction_MSE']}})
        for name in BIN_NAMES:paired.append({'split':split,'bin':name,'primary_minus_target_shuffle_control':pair_summary([r for r in rows if r['bin']==name],'primary','control')})
    result={'timestamp':stamp(),'source':snapshot(__file__),'all_passed':True,'model':key,
        'execution_sha256':sha(OUT/folder/'execution.json'),'records':all_results,'paired_comparisons':paired,
        'unique_questions':576,'native_generated_tokens':sum(r['tokens']for r in all_results if r['variant']==selection['primary_rule']),
        'not_autonomous_generation':True,'no_new_fitting_or_selection':True,'seconds':time.monotonic()-start,
        'limits':spec['limits'],'conditional_length_bins':spec['estimands']}
    immutable(final,result)
    print('NATURAL_NATIVE_HISTORY_PREDICTION_COMPLETE',key,result['native_generated_tokens'],round(result['seconds'],1),flush=True)
    for r in all_results:
        if r['variant']==selection['primary_rule']and r['split']=='diagnostic':
            for s in r['summaries']:print('NATURAL_NATIVE_HISTORY_PRIMARY',s['bin'],s['prediction_minus_training_mean'].get('equal_cohort'),flush=True)


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--model',choices=['qwen4','qwen14','glm4'],required=True);main(parser.parse_args().model)
