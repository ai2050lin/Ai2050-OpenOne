def append_memo(path,text):
    before=path.read_bytes();prefix=R.sha(path)
    numbers=re.findall(rb'^## Phase (\d+):',before,re.M);phase=int(numbers[-1])+1
    stamp=datetime.now().strftime('%Y-%m-%d %H:%M')
    text=text.replace('{PHASE}',str(phase)).replace('{STAMP}',stamp)
    assert text.splitlines()[2].encode() not in before
    with path.open('ab') as f:f.write(text.encode('utf-8'))
    after=path.read_bytes();assert after[:len(before)]==before
    return {'phase':phase,'path':str(path),'before_bytes':len(before),'after_bytes':len(after),'prefix_sha256':prefix,'new_sha256':R.sha(path),'stamp':stamp}

