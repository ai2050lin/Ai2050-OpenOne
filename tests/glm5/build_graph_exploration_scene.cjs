const path = require('node:path');
const { createRequire } = require('node:module');

const root = path.resolve(__dirname, '../..');
const frontend = path.join(root, 'frontend');
const esbuild = createRequire(path.join(frontend, 'package.json'))('esbuild');

esbuild.buildSync({
  stdin: {
    contents: `
      import { createElement } from 'react';
      import { createRoot } from 'react-dom/client';
      import Scene from './src/components/v8/AssocLayerScene.jsx';
      import { ASSOC_VIEWS } from './src/components/v8/assocLayerGeometry.js';
      import { nativeGrid } from './src/components/v8/nativeTexture.js';

      window.graphExplorationScene = {
        views: ASSOC_VIEWS,
        mount(element) {
          const root = createRoot(element);
          return ({ model, dimensions, layer, part, index, view, describe, onPick }) => {
            const objects = [
              { id: 'llm', name: model + ' · ' + dimensions.layers + ' 层' },
              { id: 'heads', name: 'Head · ' + dimensions.head, grid: [8, Math.ceil(dimensions.head / 8)], count: dimensions.head },
              { id: 'hs', name: 'HiddenState · ' + dimensions.hs, grid: nativeGrid(dimensions.hs), count: dimensions.hs },
              { id: 'mlp', name: 'MLP · ' + dimensions.mlp, grid: nativeGrid(dimensions.mlp), count: dimensions.mlp },
            ];
            root.render(createElement(Scene, {
              dims: { NL: dimensions.layers + 1, describe }, objs: objects, layer, view,
              tex: {}, marks: [{ id: part === 'head' ? 'heads' : part, idx: index }], onPick,
            }));
          };
        },
      };
    `,
    sourcefile: 'graph-exploration-scene-entry.js',
    resolveDir: frontend,
  },
  outfile: path.join(root, 'research/glm5/docs/previews/graph-exploration-scene.js'),
  banner: { js: '// Generated by tests/glm5/build_graph_exploration_scene.cjs from the client 3D component.' },
  bundle: true,
  format: 'iife',
  jsx: 'automatic',
  platform: 'browser',
  define: { 'process.env.NODE_ENV': '"production"' },
  minify: true,
  legalComments: 'eof',
});
